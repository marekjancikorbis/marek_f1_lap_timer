"""Write the app's themes from the Glass tiles palettes, so the app and the mockups can't drift apart.

    python -X utf8 apps/web/design/redesigns/tools/app_themes.py

Writes apps/web/src/styles/themes.css (one [data-theme] block per palette) and apps/web/src/lib/themes.ts (the list
the Settings picker shows). Mono comes first: it is the default.
"""
import pathlib, sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from build import PAGES  # noqa: E402

WEB = pathlib.Path(__file__).resolve().parents[3]
IDS = {'bento-mono': 'mono', 'bento-sleigh': 'navy', 'bento-pine': 'teal', 'bento-cobalt': 'lavender',
       'bento-crimson': 'red', 'bento-midnight': 'indigo', 'bento-forest': 'green'}
# app token <- palette key
KEYS = {'sea': 'sea', 'tile': 'tile', 'deep': 'deep', 'sheet': 'sheet', 'main': 'main', 'main-hi': 'main-hi',
        'on-main': 'on-main', 'accent': 'accent', 'ink': 'ink', 'ink-2': 'ink-2', 'go': 'red', 'on-go': 'on-red',
        'blob-a': 'blob-a', 'blob-b': 'blob-b', 'blob-c': 'blob-c', 'map-tint': 'map-tint'}

css = ['/* Generated by design/redesigns/tools/app_themes.py from the Glass tiles palettes. Do not edit by hand. */']
ts = ['// Generated by design/redesigns/tools/app_themes.py from the Glass tiles palettes. Do not edit by hand.',
      'export const THEMES = [']
for page, tid in IDS.items():
    _, title, pal, swatches = PAGES[page]
    body = ' '.join(f'--g-{k}: {pal.get(v, "transparent")};' for k, v in KEYS.items())
    sel = f':root, [data-theme="{tid}"]' if tid == 'mono' else f'[data-theme="{tid}"]'
    css.append(f'{sel} {{ {body} }}')
    name = title.split(' · ')[-1]
    ts.append(f"  {{ id: '{tid}', name: '{name}', swatches: {swatches!r}, page: '{pal['sea']}' }},")
ts += ['] as const;', '', "export type ThemeId = (typeof THEMES)[number]['id'];", '']
(WEB / 'src' / 'styles' / 'themes.css').write_text('\n'.join(css) + '\n', encoding='utf8')
(WEB / 'src' / 'lib' / 'themes.ts').write_text('\n'.join(ts).replace("'", "'"), encoding='utf8')
print('wrote themes.css and themes.ts:', ', '.join(IDS.values()))
